export function statusTone(value: string): StatusTone {
  const normalized = value.trim().toLocaleLowerCase('ru').replace(/ё/g, 'е').replace(/\s+/g, ' ');
  return (
    (Object.entries(statusGroups).find(([, values]) =>
      values.includes(normalized),
    )?.[0] as StatusTone) || 'neutral'
  );
}

export function feedbackTone(message: string): 'success' | 'danger' | 'info' {
  const text = message.trim().toLocaleLowerCase('ru').replace(/ё/g, 'е');
  if (/^(не удалось|ошибка|не сохранен|не добавлен|недостаточно|заполните|проверьте)/.test(text))
    return 'danger';
  if (
    /^(сохранен|добавлен|удален|обновлен|восстановлен|посещение зарегистрировано|запись снята|сообщение отправлено|палитра скопирована)/.test(
      text,
    ) ||
    /^#[0-9a-f]{6} скопирован/.test(text)
  )
    return 'success';
  return 'info';
}
