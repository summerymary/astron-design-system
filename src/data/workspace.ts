export function createWorkspaceData(): Record<string, DemoRecord[]> {
  const data: Record<string, DemoRecord[]> = structuredClone({
    ...Object.fromEntries(Object.entries(resources).map(([key, value]) => [key, value.rows])),
    ...initialExtra,
    'cash-events': demoCashMovements,
  });
  const gymPlan = data.plans.find((plan) => plan.id === 'plan-1')!;
  const periods = [
    {
      id: 'light',
      name: 'Лайт',
      accessWeekdays: '06:30–16:00, 20:00–23:10',
      accessWeekends: '07:00–22:10',
      memberId: '1006',
    },
    {
      id: 'lunch',
      name: 'Ланч',
      accessWeekdays: '12:00–15:00',
      accessWeekends: '17:00–22:10',
      memberId: '1005',
    },
  ];
  for (const period of periods) {
    const plan = {
      ...gymPlan,
      id: `plan-${period.id}`,
      name: period.name,
      accessWeekdays: period.accessWeekdays,
      accessWeekends: period.accessWeekends,
      short: `Будни ${period.accessWeekdays}; выходные ${period.accessWeekends}`,
      hours: `Пн–Пт ${period.accessWeekdays}; Сб–Вс ${period.accessWeekends}`,
      description: 'Тренажёрный зал в часы тарифа. Цена демонстрационная.',
    };
    data.plans.push(plan);
    (data['issued-plans'] ||= []).push({
      ...plan,
      id: `issued-${period.id}`,
      memberId: period.memberId,
      issued: TODAY,
    });
  }
  const youth = {
    ...gymPlan,
    id: 'plan-youth',
    name: 'Молодёжный',
    ageMin: '14',
    ageMax: '23',
    age: '14–23 года включительно',
    short: 'Тренажёрный зал · 14–23 года',
    description: 'Возраст проверяется на дату посещения. Цена демонстрационная.',
  };
  data.plans.push(youth);
  (data['issued-plans'] ||= []).push({
    ...youth,
    id: 'issued-youth',
    memberId: '1003',
    issued: TODAY,
  });
  const groupPlan = data.plans.find((plan) => plan.id === 'plan-2')!;
  (data['issued-plans'] ||= []).push({
    ...groupPlan,
    id: 'issued-group-demo',
    memberId: '1001',
    issued: TODAY,
  });
  // Fill the reference week with coherent small-group examples; Friday retains its 14 sessions.
  const weekDays = [
    '2026-11-02',
    '2026-11-03',
    '2026-11-04',
    '2026-11-05',
    '2026-11-07',
    '2026-11-08',
  ];
  const weekTimes = ['09:00', '10:30', '12:00', '13:30', '15:00', '16:30', '19:00', '20:30'];
  const weekNames = [
    'Пилатес',
    'Функциональная тренировка',
    'Здоровая спина',
    'Силовая тренировка',
  ];
  const weekCapacities = [20, 8, 6, 6, 6, 12, 6, 6];
  const weekBookings = [0, 2, 3, 5, 6, 2, 4, 6];
  for (const [dayIndex, day] of weekDays.entries()) {
    for (const [slot, time] of weekTimes.entries()) {
      const cycle = slot % 2 === 1;
      const capacity = weekCapacities[(slot + dayIndex) % weekCapacities.length];
      data.events.push({
        id: 'event-week-' + day + '-' + slot,
        demoWeek: 'true',
        name: cycle ? 'Сайкл' : weekNames[(slot / 2 + dayIndex) % weekNames.length],
        day,
        time,
        duration: cycle ? '45' : '50',
        trainer: cycle ? 'Денис Орлов' : dayIndex % 2 ? 'Максим Ветров' : 'Алина Белова',
        room: cycle ? 'Сайкл-студия' : 'Большой зал',
        club: 'Центральный',
        capacity: String(Math.min(capacity, cycle ? 12 : 20)),
        booked: String(
          Math.min(weekBookings[(slot + dayIndex * 2) % weekBookings.length], capacity),
        ),
        attendees: '',
        capacityMode: 'Своя вместимость',
        minimum: '1',
        format: 'Групповое',
        payment: 'Включено в абонемент',
        booking: 'Обычная запись',
        seats: 'Не требуется',
        waitlist: 'Включён',
        status:
          day === '2026-11-07' && slot === 2
            ? 'Отменено'
            : day < TODAY
              ? 'Завершено'
              : 'Запись открыта',
      });
    }
  }
  // Demonstration intensity is explicit and editable; colour never represents booking status.
  const low = ['Пилатес', 'Здоровая спина', 'Стретчинг', 'Мягкая йога'];
  const high = ['Функциональная тренировка', 'Сайкл'];
  for (const item of [...data.events, ...data['training-templates']]) {
    item.intensity ||= low.includes(item.name)
      ? 'Низкая'
      : high.includes(item.name)
        ? 'Высокая'
        : 'Средняя';
    item.color =
      item.intensity === 'Низкая'
        ? '#26804A'
        : item.intensity === 'Высокая'
          ? '#CE3F3F'
          : '#D4AE17';
  }
  const ids = ['1001', '1002', '1003', '1004', '1005', '1006'];
  const minute = (time: string) => {
    const [h, m] = time.split(':').map(Number);
    return h * 60 + m;
  };
  for (const event of data.events) {
    if (event.kind === 'personal') continue;
    event.description ||=
      data['training-templates'].find((template) => template.name === event.name)?.description ||
      (
        {
          Пилатес: 'Плавные упражнения на контроль движений и укрепление мышц корпуса.',
          'Мягкая йога': 'Спокойная практика с акцентом на дыхание, баланс и подвижность.',
          'Силовая тренировка': 'Силовые упражнения с небольшим оборудованием и контролем техники.',
          'Здоровая спина': 'Мягкие упражнения на подвижность и осанку.',
          Стретчинг: 'Упражнения на растяжку и развитие гибкости.',
          Сайкл: 'Кардиотренировка на велотренажёрах в темпе музыки.',
        } as Record<string, string>
      )[event.name] ||
      'Групповая тренировка под руководством тренера.';
    const available = ids.filter(
      (id) =>
        !data.events.some(
          (other) =>
            other.id !== event.id &&
            other.day === event.day &&
            other.status !== 'Отменено' &&
            (other.attendees || '').split(',').includes(id) &&
            minute(other.time) < minute(event.time) + Number(event.duration) &&
            minute(event.time) < minute(other.time) + Number(other.duration),
        ),
    );
    event.attendees = available
      .slice(
        0,
        Math.min(
          Number(event.booked),
          Number(event.capacity),
          event.demoWeek === 'true' ? ids.length : 2 + (data.events.indexOf(event) % 4),
        ),
      )
      .join(',');
    event.booked = String(event.attendees.split(',').filter(Boolean).length);
    event.present = '';
    if (!['Отменено', 'Завершено'].includes(event.status))
      event.status = Number(event.booked) >= Number(event.capacity) ? 'Мест нет' : 'Запись открыта';
  }
  data.comments = ids.map((memberId, i) => ({
    id: 'seed-comment-' + memberId,
    memberId,
    text: [
      'Предпочитает вечерние занятия.',
      'По вопросам продления удобнее связаться после 18:00.',
      'Интересуется групповыми занятиями по выходным.',
      'Уточнить удобное время для возобновления занятий.',
      'Первое знакомство с клубом, помочь с выбором занятий.',
      'Напомнить о продлении при следующем визите.',
    ][i],
    author: 'Александра Крылова',
    createdAt: '2026-10-28T18:45',
  }));
  data['client-pins'] = [{ id: '1001', commentId: 'seed-comment-1001' }];
  const reserveExample = data.events.find(
    (event) => event.day === '2026-11-08' && event.time === '15:00' && event.kind !== 'personal',
  );
  if (reserveExample) {
    reserveExample.capacityMode = 'Своя вместимость';
    reserveExample.capacity = '4';
    reserveExample.attendees = reserveExample.attendees.split(',').slice(0, 4).join(',');
    reserveExample.booked = String(reserveExample.attendees.split(',').filter(Boolean).length);
    if (Number(reserveExample.booked) === 4) {
      reserveExample.status = 'Мест нет';
      reserveExample.reserve = ids
        .filter((id) => !reserveExample.attendees.split(',').includes(id))
        .slice(0, 1)
        .join(',');
    }
  }
  return data;
}
export const money = (value: string | number) => `${Number(value || 0).toLocaleString('ru-RU')} ₽`;
export const prettyDate = (value: string) =>
  value
    ? value.split('T')[0].split('-').reverse().join('.') +
      (value.includes('T') ? ` ${value.split('T')[1]}` : '')
    : '—';
export const TODAY = '2026-11-06';
